class Q {
  const Q(
    this.id,
    this.cat,
    this.level,
    this.type,
    this.text,
    this.options,
    this.answer,
    this.explain, {
    this.picture,
    this.accept = const [],
  });

  final String id;
  final Cat cat;
  final Level level;
  final QType type;
  final L text;
  final List<L> options; // empty for fill-in-the-blank
  final int answer; // index into options
  final L explain;
  final String? picture; // a large picture (emoji) shown for picture questions
  final List<String> accept; // accepted typed answers for fill-in-the-blank

  bool checkTyped(String typed) {
    final t = typed.trim().toLowerCase().replaceAll(RegExp(r'\s+'), ' ');
    return accept.any((a) => a.toLowerCase() == t);
  }

  L get correctText => type == QType.fill ? L(accept.first, accept.length > 1 ? accept.last : accept.first) : options[answer];
}

